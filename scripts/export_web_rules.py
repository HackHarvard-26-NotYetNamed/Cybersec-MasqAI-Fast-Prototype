"""Export the gateway's detector rules and protect categories for the site's in-browser playground (/try).

    python scripts/export_web_rules.py          # writes web/lib/detector-rules.json
    python scripts/export_web_rules.py --check  # exit 1 if the committed file is stale (CI)

One source of truth: masqai/rules/*.toml and masqai/policy.py. Python regex syntax is converted to JavaScript:
named groups (?P<x>…) → (?<x>…), backreferences (?P=x) → \\k<x>, and leading inline flags (?i)(?m) → flags.
"""
from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from masqai import policy  # noqa: E402

RULES = ROOT / "masqai" / "rules"
OUT = ROOT / "web" / "lib" / "detector-rules.json"
LATE = {"email": 1, "generic_key_value": 2}   # detectors.load_rules: broad rules go last


def js_regex(pattern: str) -> dict[str, str]:
    flags = ""
    while (lead := re.match(r"\(\?([imsx]+)\)", pattern)):
        flags += lead.group(1)
        pattern = pattern[lead.end():]
    if "x" in flags:
        raise ValueError("verbose (?x) patterns have no JavaScript equivalent")
    pattern = re.sub(r"\(\?P<([A-Za-z_][A-Za-z0-9_]*)>", r"(?<\1>", pattern)
    pattern = re.sub(r"\(\?P=([A-Za-z_][A-Za-z0-9_]*)\)", r"\\k<\1>", pattern)
    return {"source": pattern, "flags": "".join(sorted(set(flags)))}


def export() -> dict:
    rules = []
    for path in sorted(RULES.glob("*.toml")):
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        for entry in data.get("rule", []):
            rules.append({"name": entry["name"], "type": entry["type"].upper(), **js_regex(entry["regex"]),
                          "group": entry.get("group", 0),
                          "ignore": [js_regex("(?i)" + p) for p in entry.get("ignore", [])]})
    rules.sort(key=lambda r: LATE.get(r["name"], 0))
    keyvalue = tomllib.loads((RULES / "keyvalue.toml").read_text(encoding="utf-8"))
    from masqai.detectors import load_rules
    generic = next(r for r in load_rules(str(RULES)) if r.name == "generic_key_value")
    return {
        "_comment": "Generated by scripts/export_web_rules.py from masqai/rules and masqai/policy.py. Do not edit.",
        "rules": rules,
        "keyvalue": {**js_regex(generic.pattern.pattern), "names": keyvalue["names"], "min_length": keyvalue.get("min_length", 8),
                     "min_length_mixed": keyvalue.get("min_length_mixed", 6), "ignore_values": keyvalue.get("ignore_values", [])},
        "categories": [{"id": c.id, "label": c.label, "kind": c.kind, "description": c.description, "types": sorted(c.types)}
                       for c in policy.CATEGORIES],
        "suffixes": [{"source": p.pattern, "category": c} for p, c in policy._SUFFIXES],
    }


def render() -> str:
    return json.dumps(export(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python scripts/export_web_rules.py", file=sys.stderr)
            sys.exit(1)
        print("web detector rules are up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}: {len(export()['rules'])} rules")
